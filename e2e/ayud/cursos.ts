import { expect, type Page } from '@playwright/test'
import { cuentas } from './datos'
import { completarAcceso, entrar } from './sesion'

export async function flujoCurso(page: Page, admin: Parameters<typeof entrar>[1]) {
  const titulo = `HU-13 Curso ${Date.now()}`
  await entrar(page, admin)
  await page.getByRole('navigation', { name: 'Navegación principal' }).getByRole('link', { name: 'Mis cursos', exact: true }).click()
  await page.getByRole('link', { name: 'Crear curso', exact: true }).click()
  await page.getByRole('textbox', { name: 'Título', exact: true }).fill(titulo)
  await page.getByLabel('Instructor asignado').selectOption({ label: 'Carlos Mendoza Ríos' })
  await page.getByLabel('Descripción', { exact: true }).fill('Curso de formación para colegiados.')
  await page.getByLabel('Horas lectivas').fill('24')
  await page.getByLabel('Modalidad').selectOption('VIRTUAL')
  await page.getByLabel('Costo (S/)').fill('150.50')
  await page.getByLabel('Cupos').fill('30')
  await page.getByLabel('Tipo de certificado').selectOption('APROBACION')
  await page.getByRole('textbox', { name: 'Módulo 1', exact: true }).fill('Práctica')
  await page.getByRole('button', { name: 'Agregar módulo', exact: true }).click()
  await page.getByRole('textbox', { name: 'Módulo 2', exact: true }).fill('Introducción')
  await page.getByRole('button', { name: 'Subir módulo 2' }).click()
  await expect(page.getByRole('textbox', { name: 'Módulo 1', exact: true })).toHaveValue('Introducción')
  await page.getByRole('button', { name: 'Guardar borrador', exact: true }).click()
  await expect(page.getByRole('heading', { name: titulo, exact: true })).toBeVisible()
  await expect(page.getByText('Borrador', { exact: true })).toBeVisible()
  await expect(page.locator('dl > div').filter({ hasText: 'Nota mínima' })).toContainText('14')
  await expect(page.getByRole('heading', { level: 3 })).toHaveText(['1. Introducción', '2. Práctica'])
  await page.getByRole('link', { name: 'Catálogo de cursos', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Catálogo de cursos' })).toBeVisible()
  await page.getByRole('textbox', { name: 'Buscar por nombre' }).fill(titulo)
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
  await expect(page.getByRole('link', { name: titulo, exact: true })).toHaveCount(0)
  await page.getByRole('navigation', { name: 'Navegación principal' }).getByRole('link', { name: 'Mis cursos', exact: true }).click()
  await page.getByRole('link', { name: titulo, exact: true }).click()
  await page.getByRole('button', { name: 'Publicar en catálogo', exact: true }).click()
  await expect(page.getByText('Publicado', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
  await completarAcceso(page, cuentas.instr)
  await page.getByRole('navigation', { name: 'Navegación principal' }).getByRole('link', { name: 'Mis cursos', exact: true }).click()
  await page.getByRole('link', { name: titulo, exact: true }).click()
  const modulo = page.getByRole('listitem').filter({ has: page.getByRole('heading', { name: '1. Introducción', exact: true }) })
  await modulo.getByLabel('Título del material').fill('Guía PDF')
  await modulo.getByLabel('Archivo PDF').setInputFiles({ name: 'guia.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\n%%EOF') })
  await modulo.getByRole('button', { name: 'Guardar material', exact: true }).click()
  await expect(modulo.getByRole('button', { name: 'Descargar PDF: Guía PDF' })).toBeVisible()
  const descarga = page.waitForEvent('download')
  await modulo.getByRole('button', { name: 'Descargar PDF: Guía PDF' }).click()
  expect((await descarga).suggestedFilename()).toBe('material.pdf')
  for (const [tipo, tituloMaterial, url] of [['ENLACE', 'Referencia', 'https://example.com/referencia'], ['VIDEO', 'Demostración', 'https://example.com/video']]) {
    await modulo.getByLabel('Tipo de material').selectOption(tipo!)
    await modulo.getByLabel('Título del material').fill(tituloMaterial!)
    await modulo.getByLabel('URL HTTPS').fill(url!)
    await modulo.getByRole('button', { name: 'Guardar material', exact: true }).click()
    await expect(modulo.getByRole('link', { name: new RegExp(tituloMaterial!) })).toHaveAttribute('href', url!)
  }
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
  await completarAcceso(page, cuentas.part)
  await page.getByRole('link', { name: 'Catálogo de cursos', exact: true }).click()
  await page.getByRole('textbox', { name: 'Buscar por nombre' }).fill(titulo)
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
  await page.getByRole('link', { name: titulo, exact: true }).click()
  await expect(page.getByRole('heading', { name: titulo, exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Guardar material', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Publicar en catálogo', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Descargar PDF: Guía PDF' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
}
