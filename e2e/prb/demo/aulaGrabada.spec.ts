import { readFile } from 'node:fs/promises'
import { test, expect } from '../../ayud/prueba'
import { cuentas } from '../../ayud/datos'
import { completarAcceso } from '../../ayud/sesion'

const tituloCurso = 'Retroalimentación que ayuda a aprender'

test('T-24: un agremiado entra al aula y descarga la constancia después de completar el curso', async ({ page }, info) => {
  await page.goto('/capacitaciones')
  const tarjeta = page.getByRole('listitem').filter({ has: page.getByRole('heading', { name: tituloCurso, exact: true }) })
  await tarjeta.getByRole('link', { name: tituloCurso, exact: true }).click({ timeout: 7000 })
  await page.getByRole('button', { name: 'Inscribirme', exact: true }).click()
  await expect(page).toHaveURL(/\/login\?curso=\d+$/)
  await completarAcceso(page, cuentas.part)
  await expect(page.getByRole('heading', { name: tituloCurso, exact: true })).toBeVisible()
  const detalle = page.url()
  await page.goto(detalle + '/aula')
  await expect(page.getByText('Confirma tu inscripción para entrar al aula.')).toBeVisible()
  await page.getByRole('link', { name: 'Volver al curso' }).click()
  await page.getByRole('button', { name: 'Inscribirme', exact: true }).click()
  const confirmacion = page.getByRole('dialog', { name: 'Confirma tu inscripción' })
  await confirmacion.getByRole('checkbox').check()
  await confirmacion.getByRole('button', { name: 'Confirmar inscripción', exact: true }).click()
  await page.getByRole('button', { name: 'Close toast' }).click()
  await page.getByRole('link', { name: 'Abrir aula grabada', exact: true }).click()

  const avance = page.getByRole('progressbar', { name: 'Avance del curso' })
  await expect(avance).toHaveAttribute('value', '0')
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('aula-grabada.png'), fullPage: true })
  await expect(page.getByRole('button', { name: 'Evaluación · Evidencia', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Descargar constancia demo', exact: true })).toBeDisabled()
  const video = page.locator('video')
  await expect(video).toBeVisible()
  await video.evaluate((elemento: HTMLVideoElement) => elemento.play())
  await expect.poll(() => video.evaluate((elemento: HTMLVideoElement) => elemento.currentTime)).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Completar lección', exact: true }).click()
  await expect(avance).toHaveAttribute('value', '1')
  await expect(page.getByRole('button', { name: 'Siguiente actividad' })).toBeFocused()
  await page.reload()
  await expect(avance).toHaveAttribute('value', '1')
  await page.goto('/participante/cursos')
  const cursoInscrito = page.getByRole('article').filter({ has: page.getByRole('heading', { name: tituloCurso, exact: true }) })
  await cursoInscrito.getByRole('link', { name: 'Continuar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Evaluación · Evidencia', exact: true })).toBeVisible()
  await page.getByRole('radio', { name: 'La cantidad de páginas del cuaderno' }).check()
  await page.getByRole('button', { name: 'Comprobar respuesta' }).click()
  await expect(page.getByText('Revisa la lección e inténtalo otra vez.')).toBeVisible()
  await expect(avance).toHaveAttribute('value', '1')
  await page.getByRole('radio', { name: 'La explicación que da el estudiante' }).check()
  await page.getByRole('button', { name: 'Comprobar respuesta' }).click()
  await expect(avance).toHaveAttribute('value', '2')
  const siguiente = page.getByRole('button', { name: 'Siguiente actividad' })
  await expect(siguiente).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Propón el siguiente paso', exact: true })).toBeFocused()
  await video.evaluate((elemento: HTMLVideoElement) => elemento.play())
  await expect.poll(() => video.evaluate((elemento: HTMLVideoElement) => elemento.currentTime)).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Completar lección', exact: true }).click()
  await page.getByRole('button', { name: 'Siguiente actividad' }).click()
  await page.getByRole('radio', { name: 'Un próximo paso concreto que el estudiante puede aplicar' }).check()
  await page.getByRole('button', { name: 'Comprobar respuesta' }).click()
  await expect(avance).toHaveAttribute('value', '4')
  const descarga = page.waitForEvent('download')
  const botonConstancia = page.getByRole('button', { name: 'Descargar constancia demo', exact: true })
  await expect(botonConstancia).toBeFocused()
  await page.keyboard.press('Enter')
  const pdf = await descarga
  expect(pdf.suggestedFilename()).toBe('constancia-aula-demo.pdf')
  const contenido = await readFile(await pdf.path(), 'ascii')
  expect(contenido).toMatch(/^%PDF-1\.4/)
  expect(contenido).toContain(Buffer.from('Documento de demostración. Sin validez oficial.', 'latin1').toString('hex'))
})
